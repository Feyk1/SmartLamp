#!/usr/bin/env python3
"""Build the static knowledge base for the rule-based dashboard assistant.

The assistant runs entirely in the browser. This script turns the public
markdown manual into a small JS array so the assistant can answer common
questions without a backend or an LLM.
"""

from __future__ import annotations

import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MANUAL = ROOT / "docs" / "manual"
OUTPUT = ROOT / "web" / "src" / "assistant-knowledge.js"
SKIP_TITLES = {
    "Back to the README",
    "Back to the manual",
    "Next",
    "Siguiente",
}


def clean_markdown(text: str) -> str:
    text = re.sub(r"```.*?```", " ", text, flags=re.S)
    text = re.sub(r"!\[[^\]]*\]\([^)]+\)", " ", text)
    text = re.sub(r"\[([^\]]+)\]\([^)]+\)", r"\1", text)
    text = re.sub(r"<(https?://[^>]+)>", r"\1", text)
    text = re.sub(r"<[^>]+>", " ", text)
    text = re.sub(r"`([^`]+)`", r"\1", text)
    text = re.sub(r"(?m)^#{1,6}\s*", "", text)
    text = text.replace("**", "").replace("__", "")
    text = re.sub(r"(?m)^\s*[-•]\s*", "• ", text)
    text = re.sub(r"(?m)^\s*\|?[\s:|-]+\|?\s*$", "", text)
    text = text.replace("|", " · ")
    text = re.sub(r"[ \t]+", " ", text)
    text = re.sub(r"\n{3,}", "\n\n", text)
    return text.strip()


def section_text(lines: list[str]) -> str:
    text = clean_markdown("\n".join(lines))
    return text[:900]


def build() -> list[dict]:
    entries: list[dict] = []
    for path in sorted(MANUAL.glob("*.md")):
        source = path.read_text(encoding="utf-8")
        lines = source.splitlines()
        page_title = path.stem.replace("-", " ").title()
        if lines and lines[0].startswith("# "):
            page_title = lines[0][2:].strip()
        current_title = None
        current_lines: list[str] = []
        in_fence = False

        def flush() -> None:
            nonlocal current_title, current_lines
            if current_title and current_title not in SKIP_TITLES:
                body = section_text(current_lines)
                if body:
                    entries.append(
                        {
                            "id": f"{path.stem}-{len(entries) + 1}",
                            "page": page_title,
                            "title": current_title,
                            "text": body,
                            "link": f"docs/manual/{path.name}",
                        }
                    )
            current_title = None
            current_lines = []

        for line in lines:
            if line.startswith("```"):
                in_fence = not in_fence
            if not in_fence and line.startswith("## "):
                flush()
                current_title = line[3:].strip()
                continue
            if current_title is not None:
                current_lines.append(line)
        flush()
    return entries


def main() -> int:
    entries = build()
    payload = json.dumps(entries, ensure_ascii=False, indent=2)
    OUTPUT.write_text(
        "/* Generated by tools/build_assistant_knowledge.py. */\n"
        "window.LAMP_ASSISTANT_KNOWLEDGE = "
        + payload
        + ";\n",
        encoding="utf-8",
    )
    print(f"Wrote {len(entries)} entries to {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
